/**
 * Build the design tokens.
 *
 *   tools/vars.json      -> raw palette ("primitives": base, primary, green…, space, radius, type)
 *   src/themes/*.json    -> themes: one complete set of --nv-* role tokens each
 *
 * Also src/styles/type.json -> the --nv-font-* and --nv-type-<role>-* tokens
 * (theme-invariant).
 *
 * Writes:
 *   src/styles/tokens.scss  `$--x: var(--x);` only. No CSS output, so every
 *                           component can import it without duplicating rules.
 *   src/styles/theme.scss   the core CSS: `:root { primitives }`, the type roles
 *                           and the DEFAULT theme only (`:root` and
 *                           `[data-theme="apollo-white"]`). Imported once by
 *                           src/index.ts, so an app gets Apollo White and nothing
 *                           else unless it asks.
 *   src/themes/css/<id>.css one `[data-theme="<id>"]` block per theme, plus
 *                           all.css. An app imports only the themes it offers
 *                           (`import '@nurvus/ui/themes/tokyo-neon.css'`); the
 *                           package build copies them to dist/themes/.
 *   The default's `:root` is wrapped in :where() (no specificity), so a
 *   theme file always wins over it, whichever stylesheet loads first.
 *   Every block sets --nv-theme-id, so setTheme can tell whether a theme's CSS
 *   is on the page.
 *
 * Then checks every theme's contrast (src/themes/roles.json → `check`). A
 * failing "demo" theme only warns; a failing "stable" theme fails the build.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const THEMES_DIR = path.join(ROOT, 'src/themes');
const DEFAULT_THEME = 'apollo-white'; // keep in step with src/themes/index.js

const primitives = JSON.parse(fs.readFileSync(path.join(__dirname, 'vars.json'), 'utf8'));
const type = JSON.parse(fs.readFileSync(path.join(ROOT, 'src/styles/type.json'), 'utf8'));
const roles = JSON.parse(fs.readFileSync(path.join(THEMES_DIR, 'roles.json'), 'utf8'));
const themes = fs.readdirSync(THEMES_DIR)
  .filter((f) => f.endsWith('.json') && f !== 'roles.json')
  .map((f) => JSON.parse(fs.readFileSync(path.join(THEMES_DIR, f), 'utf8')))
  .sort((a, b) => (a.id === DEFAULT_THEME ? -1 : b.id === DEFAULT_THEME ? 1 : a.order - b.order));

// Every theme must define every role: a missing one would silently inherit
// from whatever theme sits above it in the page.
const problems = [];
themes.forEach((t) => {
  Object.keys(roles).forEach((role) => {
    if (!t.colors[role]) problems.push(`${t.id}: missing "${role}"`);
  });
  Object.keys(t.colors).forEach((role) => {
    if (!roles[role]) problems.push(`${t.id}: "${role}" is not in roles.json`);
  });
});
if (problems.length) {
  console.error(`Theme tokens incomplete:\n  ${problems.join('\n  ')}`);
  process.exit(1);
}

const keys = Object.keys(primitives);
const scss = keys.map((key) => `$${key}: var(${key});`).join('\n');

const header = '// GENERATED by tools/build-tokens.js from tools/vars.json + src/themes/*.json. Do not edit.\n';
const primitiveBlock = `:root {\n${keys.map((key) => `  ${key}: ${primitives[key]};`).join('\n')}\n}\n`;
// Type roles (src/styles/type.json): the same in every theme.
const typeLines = [`  --nv-font-sans: ${type.font.sans};`, `  --nv-font-mono: ${type.font.mono};`];
Object.entries(type.roles).forEach(([role, t]) => ['size', 'line', 'weight', 'tracking'].forEach((k) => typeLines.push(`  --nv-type-${role}-${k}: ${t[k]};`)));
const typeBlock = `:root {\n${typeLines.join('\n')}\n}\n`;
const themeBlock = (t, selector) => {
  const lines = Object.keys(roles).map((role) => `  --nv-${role}: ${t.colors[role]};`);
  return `/* ${t.name}: ${t.keywords} (${t.mode}, ${t.status}) */\n${selector} {\n  color-scheme: ${t.mode};\n  --nv-theme-id: ${t.id};\n${lines.join('\n')}\n}\n`;
};
const defaultTheme = themes.find((t) => t.id === DEFAULT_THEME);
const cssHeader = '/* GENERATED by tools/build-tokens.js from src/themes/*.json. Do not edit. */\n';

fs.writeFileSync(path.join(ROOT, 'src/styles/tokens.scss'), `${header}${scss}\n`);
fs.writeFileSync(path.join(ROOT, 'src/styles/theme.scss'), `${header}\n${primitiveBlock}\n${typeBlock}\n${themeBlock(defaultTheme, `:where(:root),\n[data-theme="${DEFAULT_THEME}"]`)}`);
// One file per theme (opt-in), and all.css for apps that offer every theme.
const CSS_DIR = path.join(THEMES_DIR, 'css');
fs.mkdirSync(CSS_DIR, { recursive: true });
fs.readdirSync(CSS_DIR).filter((f) => f.endsWith('.css')).forEach((f) => fs.unlinkSync(path.join(CSS_DIR, f)));
themes.forEach((t) => fs.writeFileSync(path.join(CSS_DIR, `${t.id}.css`), `${cssHeader}${themeBlock(t, `[data-theme="${t.id}"]`)}`));
fs.writeFileSync(path.join(CSS_DIR, 'all.css'), `${cssHeader}${themes.map((t) => themeBlock(t, `[data-theme="${t.id}"]`)).join('\n')}`);
console.log(`Tokens: ${keys.length} primitives, ${themes.length} themes × ${Object.keys(roles).length} role tokens.`);

// Contrast check (WCAG 2). contrast.mjs is an ES module, so load it with import().
import('./contrast.mjs').then(({ checkTheme }) => {
  let blocking = 0;
  themes.forEach((t) => {
    const fails = checkTheme(t, roles).filter((row) => !row.pass);
    if (!fails.length) {
      console.log(`  ✓ ${t.name}: every contrast check passes`);
      return;
    }
    const stable = t.status === 'stable';
    if (stable) blocking += fails.length;
    console.log(`  ${stable ? '✗' : '!'} ${t.name} (${t.status}): ${fails.map((f) => `${f.token} on ${f.against} ${f.ratio.toFixed(2)}:1 < ${f.min}`).join('; ')}`);
  });
  if (blocking) {
    console.error(`${blocking} contrast failure(s) in stable themes.`);
    process.exit(1);
  }
});
